import 'dart:typed_data';

/// 激活码校验密钥。
///
/// 拆成三份异或存放，避免 `strings` 一类的工具直接把密钥翻出来。
/// **注意**：这仍然是「密钥在客户端」的方案 —— 有人愿意逆向就能拿到它并
/// 伪造激活码。对纯离线应用来说这是无法避免的取舍：真正的防护需要联网校验。
/// 好在要绕过的人也完全可以改包，两种做法的实际防护等级差别不大，
/// 换来的是「激活码 24 个字符、能手输」的可用性。
const List<int> _shareA = <int>[
  92, 86, 75, 202, 1, 97, 155, 248,
  27, 171, 40, 112, 248, 124, 55, 178,
  122, 198, 23, 191, 22, 201, 76, 111,
  88, 235, 99, 90, 91, 53, 54, 114,
];

const List<int> _shareB = <int>[
  124, 113, 12, 157, 215, 181, 148, 116,
  201, 222, 191, 56, 91, 42, 173, 117,
  35, 169, 182, 127, 60, 8, 153, 66,
  113, 74, 109, 53, 100, 177, 130, 217,
];

const List<int> _shareC = <int>[
  54, 136, 141, 239, 119, 215, 255, 112,
  29, 26, 14, 30, 173, 99, 51, 88,
  66, 172, 160, 33, 133, 249, 89, 111,
  134, 74, 70, 118, 247, 146, 66, 95,
];

/// 还原 32 字节密钥
Uint8List licenseSecret() {
  final out = Uint8List(_shareA.length);
  for (var i = 0; i < out.length; i++) {
    out[i] = _shareA[i] ^ _shareB[i] ^ _shareC[i];
  }
  return out;
}
